import type { KnowledgeEntry, KnowledgePack } from "../knowledge-pack-schema.ts";
import { agentkitSource } from "../knowledge-sources.ts";

const CREATIVITY = "kits/marketing/skills/ak-creativity";

/** One row of the visual style registry. */
function style(
  id: string,
  title: string,
  text: string,
  f: {
    keywords: string;
    palette: string;
    signatureEffects: string;
    music: string;
    voiceStyle: string;
    bestFor: string;
    avoidFor: string;
  },
): KnowledgeEntry {
  return { id, title, text, fields: f, tags: ["visual-style"] };
}

/** One row of the voice-over style registry. */
function voice(
  id: string,
  title: string,
  text: string,
  f: {
    tone: string;
    delivery: string;
    pacing: string;
    pitch: string;
    energy: string;
    bestFor: string;
    directionKeywords: string;
  },
): KnowledgeEntry {
  return { id, title, text, fields: f, tags: ["voiceover-style"] };
}

/** One colour of the colour psychology table. */
function color(
  id: string,
  title: string,
  f: { emotion: string; bestFor: string; caution: string },
): KnowledgeEntry {
  return {
    id,
    title,
    text: `Reads as ${f.emotion.toLowerCase()}; a hypothesis to fit to the brief, not a guaranteed effect.`,
    fields: f,
    tags: ["color"],
  };
}

/** One campaign category of the creative reasoning table; `styles` are ids of the visual style registry. */
function campaign(
  id: string,
  title: string,
  styles: readonly [string, string],
  f: {
    colorMood: string;
    musicMood: string;
    voiceStyle: string;
    keyEffects: string;
    platformPriority: string;
    audience: string;
    decisionRules: string;
    antiPatterns: string;
    severity: "high" | "medium";
  },
): KnowledgeEntry {
  return {
    id: `campaign-${id}`,
    title,
    text: `Lead with ${styles.join(" and ")}. ${f.decisionRules} Avoid: ${f.antiPatterns}.`,
    fields: { stylePriority: styles.join(", "), ...f },
    tags: ["campaign-reasoning"],
  };
}

/** One music genre whose source note states how it is licensed; `styleMatch` lists visual style ids. */
function music(
  id: string,
  title: string,
  f: {
    mood: string;
    bpm: string;
    instruments: string;
    bestFor: string;
    styleMatch: string;
    avoidFor: string;
    licence: string;
  },
): KnowledgeEntry {
  return {
    id: `music-${id}`,
    title,
    text: `${f.mood}; ${f.instruments.toLowerCase()}. Licence route: ${f.licence.toLowerCase()}.`,
    fields: f,
    tags: ["music"],
  };
}

