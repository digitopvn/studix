const EXAMPLES_URL = "https://threejs.org/examples/";

/** `[file without .html, name, complexity, use cases]`, as listed by the source index. */
type ExampleRow = readonly [file: string, name: string, complexity: string, useCases: string];

function example(category: string, [file, name, complexity, useCases]: ExampleRow): KnowledgeEntry {
  const topics = name.split("/").map((t) => t.trim());
  return {
    id: `example-${file.replaceAll("_", "-")}`,
    title: name,
    text: `Three.js ${category} example demonstrating ${topics.join(", ")}.`,
    fields: { category, file: `${file}.html`, url: `${EXAMPLES_URL}${file}.html`, complexity, useCases },
    tags: ["threejs-example", ...topics],
  };
}

