import { readFileSync } from "node:fs";
import { StudixError } from "@studix/shared";
import type { Shot, VideoIR } from "@studix/video-ir";
import {
  HTML_CARD_MIME,
  HtmlCardPackage,
  htmlCardProblems,
  namespaceSelector,
  sanitizeHtmlCard,
} from "./html-card.ts";
import { cssRule, num, scriptJson, seconds } from "./html-utils.ts";

type CompositionShot = Extract<Shot, { type: "composition" }>;

/** Composition shots whose code asset is an HTML card, keyed by asset id. */
export function htmlCardAssetIds(ir: VideoIR): Set<string> {
  const cards = new Set(ir.assets.filter((a) => a.mime === HTML_CARD_MIME).map((a) => a.id));
  const used = new Set<string>();
  for (const scene of ir.scenes)
    for (const shot of scene.shots)
      if (shot.type === "composition" && cards.has(shot.assetId)) used.add(shot.assetId);
  return used;
}

/** Whether `shot` is a composition shot that names an HTML card asset of `ir`. */
export function isHtmlCardShot(ir: VideoIR, shot: Shot): boolean {
  if (shot.type !== "composition") return false;
  return ir.assets.some((a) => a.id === shot.assetId && a.mime === HTML_CARD_MIME);
}

/**
 * Read, parse and safety-check every HTML card the IR uses. Anything wrong is a VALIDATION error that lists
 * the problems, so a broken card never reaches the browser.
 */
export function loadHtmlCards(
  ir: VideoIR,
  assetFiles: Readonly<Record<string, string>> | undefined,
): Map<string, HtmlCardPackage> {
  const cards = new Map<string, HtmlCardPackage>();
  for (const assetId of [...htmlCardAssetIds(ir)].sort()) {
    const file = assetFiles?.[assetId];
    if (!file) throw cardError(assetId, "no local file for the code asset", ["missing code asset file"]);
    let raw: unknown;
    try {
      raw = JSON.parse(readFileSync(file, "utf8"));
    } catch (err) {
      const reason = err instanceof Error ? err.message : String(err);
      throw cardError(assetId, "the code asset is not readable JSON", [reason], err);
    }
    const parsed = HtmlCardPackage.safeParse(raw);
    if (!parsed.success) {
      const issues = parsed.error.issues.map((i) => `${i.path.join(".") || "/"}: ${i.message}`);
      throw cardError(assetId, "the code asset is not a valid HTML card package", issues);
    }
    const problems = htmlCardProblems(parsed.data);
    if (problems.length > 0) throw cardError(assetId, "the card breaks the safety rules", problems);
    cards.set(assetId, parsed.data);
  }
  return cards;
}

function cardError(assetId: string, message: string, problems: string[], cause?: unknown): StudixError {
  return new StudixError("VALIDATION", `HTML card "${assetId}": ${message}`, {
    retryable: false,
    cause,
    details: { assetId, problems },
    suggestedAction:
      "Fix the card so htmlCardProblems() and lintHtmlCard() report nothing, then store it again.",
  });
}

/**
 * Card layer markup and CSS: the sanitized, id-namespaced card over the full frame, hidden until its shot
 * window. The base rule comes after the agent's card-level declarations, so it always wins on placement,
 * clipping (paint containment also holds fixed-position children) and the opacity the shot motion drives.
 */
export function htmlCardMarkup(
  id: string,
  pkg: HtmlCardPackage,
  fontStacks: { heading: string; body: string },
): { html: string; css: string[] } {
  const card = sanitizeHtmlCard(pkg, id);
  if (card.problems.length > 0) {
    throw new StudixError("VALIDATION", "HTML card breaks the safety rules", {
      retryable: false,
      details: { problems: card.problems },
    });
  }
  return {
    html: `<div id="${id}" class="html-card">${card.html}</div>`,
    css: [
      ...(card.css ? [card.css] : []),
      cssRule(`#${id}`, [
        "position: absolute;",
        "inset: 0;",
        "overflow: hidden;",
        "contain: paint;",
        "box-sizing: border-box;",
        "opacity: 0;",
        `--font-heading: ${fontStacks.heading};`,
        `--font-body: ${fontStacks.body};`,
        "font-family: var(--font-body);",
      ]),
    ],
  };
}

/**
 * The card tweens as scene timeline statements, generated by Studix from validated data: every value is
 * JSON-encoded and targets are resolved inside the card. The tweens fill a sub-timeline (times in seconds
 * from the card start) placed on the scene timeline at the shot start. A target tweened again does not
 * render its start state at creation, so seeking stays exact (same rule as TimelineWriter).
 */
export function htmlCardScript(id: string, shot: CompositionShot, pkg: HtmlCardPackage): string[] {
  const started = new Set<string>();
  const lines = pkg.tweens.map((tween) => {
    const target = namespaceSelector(tween.target, id);
    const timing: Record<string, string | number | boolean> = { duration: tween.duration };
    if (tween.ease) timing.ease = tween.ease;
    if (tween.stagger !== undefined) timing.stagger = tween.stagger;
    if (started.has(target) && tween.from) timing.immediateRender = false;
    started.add(target);
    const at = num(tween.at);
    const call =
      tween.from && tween.to
        ? `sub.fromTo(q, ${scriptJson(tween.from)}, ${scriptJson({ ...tween.to, ...timing })}, ${at})`
        : tween.from
          ? `sub.from(q, ${scriptJson({ ...tween.from, ...timing })}, ${at})`
          : `sub.to(q, ${scriptJson({ ...tween.to, ...timing })}, ${at})`;
    return `  q = root.querySelectorAll(${scriptJson(target)}); if (q.length) ${call};`;
  });
  return [
    "(function () {",
    "  var sub = gsap.timeline();",
    `  var root = document.getElementById(${scriptJson(id)});`,
    "  var q;",
    ...lines,
    `  tl.add(sub, ${num(seconds(shot.startMs))});`,
    "})();",
  ];
}
