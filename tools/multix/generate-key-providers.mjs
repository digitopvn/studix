#!/usr/bin/env node
// Regenerate packages/providers/src/multix-key-providers.generated.ts from the multix CLI, so the vendor keys
// Studix stores and injects follow multix instead of a hand-kept list. Run it after bumping MULTIX_COMMIT:
//   MULTIX_BIN=/path/to/multix/dist/cli.js pnpm multix:keys
// `multix catalog providers` reads multix's own tables: no key is needed and nothing is paid.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const bin = process.env.MULTIX_BIN?.trim();
if (!bin) {
  console.error("Set MULTIX_BIN to the multix CLI (its dist/cli.js).");
  process.exit(1);
}
const [command, prefix] = /\.(c|m)?js$/i.test(bin) ? [process.execPath, [bin]] : [bin, []];
const stdout = execFileSync(command, [...prefix, "catalog", "providers", "--json"], {
  encoding: "utf8",
  maxBuffer: 16 * 1024 * 1024,
  env: { ...process.env, MULTIX_DISABLE_HOME_ENV: "1" },
  stdio: ["ignore", "pipe", "ignore"],
});
const line = stdout
  .split(/\r?\n/)
  .reverse()
  .find((l) => l.trim().startsWith("{"));
const body = JSON.parse(line ?? "{}");
const providers = body.data?.providers ?? body.providers;
if (!Array.isArray(providers)) throw new Error("multix catalog providers --json returned no providers");
const keyed = providers.filter((p) => Array.isArray(p.keys) && p.keys.length > 0);
if (keyed.length === 0) {
  throw new Error(
    "This multix does not list provider keys; it needs mrgoonie/multix-cli#571 (catalog `keys`).",
  );
}
const rows = keyed
  .map((p) => ({ id: p.id, name: p.name, keys: p.keys }))
  .sort((a, b) => a.id.localeCompare(b.id));
const version = execFileSync(command, [...prefix, "--version"], { encoding: "utf8" }).trim();

const out = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../../packages/providers/src/multix-key-providers.generated.ts",
);
writeFileSync(
  out,
  `// Generated by tools/multix/generate-key-providers.mjs from \`multix catalog providers --json\` (multix ${version}).
// Do not edit by hand: run \`pnpm multix:keys\` against the pinned multix instead.

/** Every multix provider that reads a key: rows are all required, the names in a row are alternatives. */
export const MULTIX_KEY_PROVIDERS = ${JSON.stringify(rows, null, 2)} as const satisfies readonly {
  id: string;
  name: string;
  keys: readonly (readonly string[])[];
}[];
`,
);
console.log(`Wrote ${rows.length} providers to ${out}`);
